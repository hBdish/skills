#!/usr/bin/env python3
"""Install skills from this repo into any project, for any agent, on any OS.

    python3 scripts/install.py --list
    python3 scripts/install.py --profile python                  # into the current project
    python3 scripts/install.py --profile python --project ../api # into another project
    python3 scripts/install.py --profile everyone --global       # into the user's home
    python3 scripts/install.py --skill python-style --agent claude --agent universal
    python3 scripts/install.py --profile python --copy           # no links (CI, sandboxes, devcontainers)
    python3 scripts/install.py --profile python --agents-md      # also index skills in AGENTS.md
    python3 scripts/install.py --profile python --uninstall
    python3 scripts/install.py --profile python --dry-run

Model: one canonical source (skills/<group>/<name>); agent directories get a
link to it, so `git pull` here updates every project at once. Link type per OS:
symlink on macOS/Linux; on Windows a symlink if allowed (Developer Mode),
otherwise a directory junction (no admin needed), otherwise a copy.

Install by profile, not "everything": every installed skill's description sits
in the agent's context on every request.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Tuple

from _skills import REPO, FrontmatterError, discover, load_profiles, parse_frontmatter

# agent -> (project dir, global dir). Most agents now read the shared
# .agents/skills; the rest have their own. This is the fragile part: verify
# against the agent's docs when it updates (`npx skills` keeps a long list).
AGENTS: Dict[str, Tuple[str, str]] = {
    # Codex, Cursor, Gemini CLI, GitHub Copilot, OpenCode, Amp, Cline, Warp, Zed, ...
    "universal": (".agents/skills", "~/.agents/skills"),
    "claude": (".claude/skills", "~/.claude/skills"),
    "cursor": (".agents/skills", "~/.cursor/skills"),
    "gemini": (".agents/skills", "~/.gemini/skills"),
    "copilot": (".agents/skills", "~/.copilot/skills"),
    "opencode": (".agents/skills", "~/.config/opencode/skills"),
    "windsurf": (".windsurf/skills", "~/.codeium/windsurf/skills"),
    "kiro": (".kiro/skills", "~/.kiro/skills"),
    "roo": (".roo/skills", "~/.roo/skills"),
    "junie": (".junie/skills", "~/.junie/skills"),
    "goose": (".goose/skills", "~/.config/goose/skills"),
}
DEFAULT_AGENTS = ["universal", "claude"]

# Left in copied skills so --uninstall only ever deletes what it created.
MARKER = ".installed-by-skills-repo"
COPY_IGNORE = shutil.ignore_patterns("evals", "__pycache__", "*.pyc", ".DS_Store")

AGENTS_MD_START = "<!-- skills:start (generated by install.py --agents-md) -->"
AGENTS_MD_END = "<!-- skills:end -->"


def is_link(p: Path) -> bool:
    """Symlink or Windows junction (os.path.islink is False for junctions before 3.12)."""
    if p.is_symlink():
        return True
    if os.name == "nt" and p.exists():
        return os.path.realpath(p) != os.path.join(os.path.realpath(p.parent), p.name)
    return False


def managed(p: Path) -> bool:
    if is_link(p):
        return REPO in Path(os.path.realpath(p)).parents
    return (p / MARKER).exists()


def remove(p: Path) -> None:
    if is_link(p):
        # Never rmtree a link: that would delete the skill in this repo.
        try:
            p.unlink()
        except OSError:  # Windows directory symlinks and junctions go via rmdir
            os.rmdir(p)
    else:
        shutil.rmtree(p)


def link_or_copy(src: Path, dst: Path, copy: bool) -> str:
    if not copy:
        try:
            dst.symlink_to(src, target_is_directory=True)
            return "symlink"
        except OSError:
            if os.name == "nt":
                res = subprocess.run(["cmd", "/c", "mklink", "/J", str(dst), str(src)], capture_output=True)
                if res.returncode == 0:
                    return "junction"
    shutil.copytree(src, dst, ignore=COPY_IGNORE)
    (dst / MARKER).write_text(f"source: {src}\nre-run install.py to update this copy\n", encoding="utf-8")
    return "copy"


def update_agents_md(project: Path, installed_dir: str, dry: bool) -> None:
    """Index the skills present in installed_dir in the project's AGENTS.md.

    For agents that read AGENTS.md but have no skill support. It is an index,
    not a concatenation: the agent opens a SKILL.md only when the task matches,
    which keeps progressive disclosure working. Built from what is on disk, so
    repeated installs of different profiles and uninstalls stay in sync.
    """
    rows = []
    for skill_md in sorted((project / installed_dir).glob("*/SKILL.md")):
        try:
            meta, _ = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        except (FrontmatterError, UnicodeDecodeError):
            continue
        name = skill_md.parent.name
        rows.append(f"- `{name}` (`{installed_dir}/{name}/SKILL.md`): {meta.get('description', '')}")
    block = (
        f"{AGENTS_MD_START}\n## Skills\n\n"
        "Before a task, check this list. If a skill matches, read its SKILL.md and follow it;\n"
        "load files it references only when the step needs them.\n\n"
        + "\n".join(rows) + f"\n{AGENTS_MD_END}"
    ) if rows else ""
    path = project / "AGENTS.md"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if AGENTS_MD_START in text and AGENTS_MD_END in text:
        head, rest = text.split(AGENTS_MD_START, 1)
        new = (head + block + rest.split(AGENTS_MD_END, 1)[1]).rstrip() + "\n"
    elif rows:
        new = (text.rstrip() + "\n\n" if text.strip() else "") + block + "\n"
    else:
        return
    print(f"  ~ AGENTS.md: {len(rows)} skills indexed{' (dry-run)' if dry else ''}")
    if not dry:
        path.write_text(new, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-p", "--profile", action="append", default=[], help="profile from profiles.json (repeatable)")
    ap.add_argument("-s", "--skill", action="append", default=[], help="single skill by name (repeatable)")
    ap.add_argument("-a", "--agent", action="append", default=[], choices=sorted(AGENTS),
                    help=f"target agent (repeatable, default: {' '.join(DEFAULT_AGENTS)})")
    ap.add_argument("-g", "--global", dest="global_", action="store_true", help="install into the home directory")
    ap.add_argument("--project", type=Path, default=Path.cwd(), help="project root (default: current directory)")
    ap.add_argument("--copy", action="store_true", help="copy instead of linking")
    ap.add_argument("--agents-md", action="store_true", help="add/refresh a skills index in the project's AGENTS.md")
    ap.add_argument("--uninstall", action="store_true")
    ap.add_argument("--force", action="store_true", help="replace existing skill dirs not created by this script")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--list", action="store_true", help="show skills, profiles and agents")
    args = ap.parse_args()

    all_skills = {s.name: s for s in discover()}
    profiles = load_profiles()

    if args.list:
        print("skills:")
        for s in all_skills.values():
            print(f"  {s.name:<24} {s.group}")
        print("\nprofiles:")
        for name, members in profiles.items():
            print(f"  {name:<24} {' '.join(members) or '(empty)'}")
        print("\nagents (project dir | global dir):")
        for name, (proj, glob) in AGENTS.items():
            print(f"  {name:<24} {proj:<20} {glob}")
        return 0

    wanted: List[str] = []
    for prof in args.profile:
        if prof not in profiles:
            print(f"unknown profile {prof!r}; see --list", file=sys.stderr)
            return 2
        wanted += profiles[prof]
    wanted += args.skill
    wanted = list(dict.fromkeys(wanted))
    if not wanted:
        print("nothing to install: pass --profile or --skill (see --list)", file=sys.stderr)
        return 2
    missing = [w for w in wanted if w not in all_skills]
    if missing:
        print(f"unknown skills: {' '.join(missing)}", file=sys.stderr)
        return 2
    broken = [w for w in wanted if all_skills[w].error]
    if broken:
        print(f"skills with invalid SKILL.md, run scripts/validate.py: {' '.join(broken)}", file=sys.stderr)
        return 2

    project = args.project.resolve()
    if not args.global_ and project == REPO:
        print("refusing to install into the skills repo itself; pass --project or cd into a project", file=sys.stderr)
        return 2

    targets: Dict[Path, List[str]] = {}
    for agent in args.agent or DEFAULT_AGENTS:
        proj_dir, glob_dir = AGENTS[agent]
        base = Path(os.path.expanduser(glob_dir)) if args.global_ else project / proj_dir
        targets.setdefault(base, []).append(agent)

    print(f"source:  {REPO}")
    print(f"scope:   {'global' if args.global_ else project}")
    print(f"skills:  {' '.join(wanted)}")
    print()

    for base, agents in targets.items():
        print(f"{base}  [{', '.join(agents)}]")
        if not args.dry_run and not args.uninstall:
            base.mkdir(parents=True, exist_ok=True)
        for name in wanted:
            src, dst = all_skills[name].path, base / name
            exists = dst.exists() or dst.is_symlink()
            if exists and not managed(dst) and not args.force:
                print(f"  ! {name}: {dst} exists and was not installed from this repo; skipped (--force to replace)")
                continue
            if args.uninstall:
                if exists and not args.dry_run:
                    remove(dst)
                print(f"  - {name}" + ("" if exists else " (not installed)"))
                continue
            if args.dry_run:
                print(f"  ~ {name}")
                continue
            if exists:
                remove(dst)
            print(f"  + {name} ({link_or_copy(src, dst, args.copy)})")

    if args.agents_md and not args.global_:
        agents = args.agent or DEFAULT_AGENTS
        installed_dir = AGENTS["universal" if "universal" in agents else agents[0]][0]
        update_agents_md(project, installed_dir, args.dry_run)

    print("\ndry-run: nothing changed." if args.dry_run else "\ndone. restart the agent so it rescans its skills.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
